package c

// This fork intentionally supports only the SQLite types and commands used by
// Procmac. Reject unsupported SQL rather than emit misleading C bindings.
import (
	"bytes"
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/sqlc-dev/plugin-sdk-go/plugin"
)

func cIdentifier(s string) bool {
	if s == "" || !(s[0] == '_' || s[0] >= 'A' && s[0] <= 'Z' || s[0] >= 'a' && s[0] <= 'z') {
		return false
	}
	for _, c := range s {
		if c > unicode.MaxASCII || !(c == '_' || c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9') {
			return false
		}
	}
	for _, keyword := range strings.Fields("auto break case char const continue default do double else enum extern float for goto if inline int long register restrict return short signed sizeof static struct switch typedef union unsigned void volatile while _Bool _Complex _Imaginary") {
		if s == keyword {
			return false
		}
	}
	return true
}

func generateSQLite(req *plugin.GenerateRequest) (*plugin.GenerateResponse, error) {
	var h, c bytes.Buffer
	fmt.Fprintln(&h, "/* Generated by sqlc-gen-c. Do not edit. */\n#ifndef PROCMAC_SQLC_QUERIES_H\n#define PROCMAC_SQLC_QUERIES_H\n#include <stdint.h>\n#include <sqlite3.h>")
	fmt.Fprintln(&c, "/* Generated by sqlc-gen-c. Do not edit. */\n#include \"queries.h\"\n#include <stdlib.h>\n#include <string.h>")
	hasText := false
	for _, query := range req.Queries {
		if query != nil && query.Cmd == ":one" {
			for _, column := range query.Columns {
				if column != nil && column.Type != nil && strings.EqualFold(column.Type.Name, "text") {
					hasText = true
				}
			}
		}
	}
	if hasText {
		fmt.Fprintln(&c, `
static int
copy_text(sqlite3_stmt *stmt, int column, int nullable, char **out)
{
	int type = sqlite3_column_type(stmt, column);
	if (type == SQLITE_NULL && nullable) {
		*out = NULL;
		return SQLITE_OK;
	}
	if (type != SQLITE_TEXT)
		return SQLITE_MISMATCH;
	const unsigned char *text = sqlite3_column_text(stmt, column);
	if (!text)
		return SQLITE_NOMEM;
	int size = sqlite3_column_bytes(stmt, column);
	if (size < 0 || memchr(text, 0, (size_t)size))
		return SQLITE_MISMATCH;
	char *copy = malloc((size_t)size + 1);
	if (!copy)
		return SQLITE_NOMEM;
	memcpy(copy, text, (size_t)size);
	copy[size] = 0;
	*out = copy;
	return SQLITE_OK;
}`)
	}
	seenQueries := map[string]bool{}
	for _, q := range req.Queries {
		if q == nil {
			return nil, fmt.Errorf("nil query")
		}
		if !cIdentifier(q.Name) || seenQueries[q.Name] {
			return nil, fmt.Errorf("invalid or duplicate query name %q", q.Name)
		}
		seenQueries[q.Name] = true
		if q.Cmd != ":exec" && q.Cmd != ":one" {
			return nil, fmt.Errorf("query %s: unsupported command %s", q.Name, q.Cmd)
		}
		for _, r := range q.Text {
			if r > 126 || (r < 32 && r != '\n' && r != '\r' && r != '\t') {
				return nil, fmt.Errorf("query %s: only ASCII SQL is supported", q.Name)
			}
		}
		params := append([]*plugin.Parameter(nil), q.Params...)
		for _, param := range params {
			if param == nil {
				return nil, fmt.Errorf("query %s: nil parameter", q.Name)
			}
		}
		sort.Slice(params, func(i, j int) bool { return params[i].Number < params[j].Number })
		args := "sqlite3 *db"
		for i, p := range params {
			if p.Number != int32(i+1) || p.Column == nil || p.Column.Type == nil || !strings.EqualFold(p.Column.Type.Name, "text") || p.Column.IsArray || p.Column.IsSqlcSlice {
				return nil, fmt.Errorf("query %s: only contiguous TEXT parameters are supported", q.Name)
			}
			args += fmt.Sprintf(", const char *p%d", p.Number)
		}
		row := "pcsql_" + q.Name + "_row"
		if q.Cmd == ":one" {
			if len(q.Columns) == 0 {
				return nil, fmt.Errorf("query %s: expected result columns", q.Name)
			}
			fmt.Fprintf(&h, "\ntypedef struct %s {\n", row)
			fields := map[string]bool{}
			for _, col := range q.Columns {
				if col == nil || !cIdentifier(col.Name) || fields[col.Name] || col.Type == nil || col.IsArray || col.EmbedTable != nil {
					return nil, fmt.Errorf("query %s: invalid or duplicate result column", q.Name)
				}
				fields[col.Name] = true
				switch strings.ToLower(col.Type.Name) {
				case "text":
					fmt.Fprintf(&h, "\tchar *%s;\n", col.Name)
				case "integer":
					if !col.NotNull {
						return nil, fmt.Errorf("query %s: nullable integer not supported", q.Name)
					}
					fmt.Fprintf(&h, "\tint64_t %s;\n", col.Name)
				default:
					return nil, fmt.Errorf("query %s: unsupported result type %s", q.Name, col.Type.Name)
				}
			}
			fmt.Fprintf(&h, "} %s;\nvoid pcsql_%s_free(%s *row);\n", row, q.Name, row)
			fmt.Fprintf(&c, "\nvoid\npcsql_%s_free(%s *row)\n{\n\tif (!row)\n\t\treturn;\n", q.Name, row)
			for _, col := range q.Columns {
				if strings.EqualFold(col.Type.Name, "text") {
					fmt.Fprintf(&c, "\tfree(row->%s);\n", col.Name)
				}
			}
			fmt.Fprintln(&c, "\tmemset(row, 0, sizeof(*row));\n}")
			args += ", " + row + " *out"
		} else {
			args += ", int *changed"
		}
		fmt.Fprintf(&h, "int pcsql_%s(%s);\n", q.Name, args)
		fmt.Fprintf(&c, "\nint\npcsql_%s(%s)\n{\n", q.Name, args)
		if q.Cmd == ":one" {
			fmt.Fprintf(&c, "\t%s row = {0};\n\tif (!db || !out)\n\t\treturn SQLITE_MISUSE;\n", row)
		} else {
			fmt.Fprintln(&c, "\tif (!db || !changed)\n\t\treturn SQLITE_MISUSE;\n\t*changed = 0;")
		}
		for _, p := range params {
			fmt.Fprintf(&c, "\tif (!p%d)\n\t\treturn SQLITE_MISUSE;\n", p.Number)
		}
		fmt.Fprintf(&c, "\tsqlite3_stmt *stmt = NULL;\n\tint rc = sqlite3_prepare_v2(db, %s, -1, &stmt, NULL);\n\tif (rc != SQLITE_OK)\n\t\tgoto done;\n", strconv.Quote(q.Text))
		for _, p := range params {
			fmt.Fprintf(&c, "\trc = sqlite3_bind_text(stmt, %d, p%d, -1, SQLITE_TRANSIENT);\n\tif (rc != SQLITE_OK)\n\t\tgoto done;\n", p.Number, p.Number)
		}
		fmt.Fprintln(&c, "\trc = sqlite3_step(stmt);")
		if q.Cmd == ":exec" {
			fmt.Fprintln(&c, "\tif (rc == SQLITE_DONE) {\n\t\t*changed = sqlite3_changes(db);\n\t\trc = SQLITE_OK;\n\t}")
		} else {
			fmt.Fprintln(&c, "\tif (rc == SQLITE_DONE) {\n\t\trc = SQLITE_NOTFOUND;\n\t\tgoto done;\n\t}\n\tif (rc != SQLITE_ROW)\n\t\tgoto done;")
			for i, col := range q.Columns {
				if strings.EqualFold(col.Type.Name, "text") {
					nullable := 0
					if !col.NotNull {
						nullable = 1
					}
					fmt.Fprintf(&c, "\trc = copy_text(stmt, %d, %d, &row.%s);\n\tif (rc != SQLITE_OK)\n\t\tgoto done;\n", i, nullable, col.Name)
				} else {
					fmt.Fprintf(&c, "\tif (sqlite3_column_type(stmt, %d) != SQLITE_INTEGER) {\n\t\trc = SQLITE_MISMATCH;\n\t\tgoto done;\n\t}\n\trow.%s = sqlite3_column_int64(stmt, %d);\n", i, col.Name, i)
				}
			}
			fmt.Fprintln(&c, "\trc = SQLITE_OK;")
		}
		fmt.Fprintln(&c, "done:\n\tif (stmt) {\n\t\tint end = sqlite3_finalize(stmt);\n\t\tif (rc == SQLITE_OK && end != SQLITE_OK)\n\t\t\trc = end;\n\t}")
		if q.Cmd == ":one" {
			fmt.Fprintf(&c, "\tif (rc == SQLITE_OK)\n\t\t*out = row;\n\telse\n\t\tpcsql_%s_free(&row);\n", q.Name)
		}
		fmt.Fprintln(&c, "\treturn rc;\n}")
	}
	fmt.Fprintln(&h, "\n#endif")
	return &plugin.GenerateResponse{Files: []*plugin.File{{Name: "queries.h", Contents: h.Bytes()}, {Name: "queries.c", Contents: c.Bytes()}}}, nil
}
